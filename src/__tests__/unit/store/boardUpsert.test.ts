/**
 * The board upsert's `set` list, against the table it is a mirror of.
 *
 * MEASURED, and this is the defect that earned the test. `board_row.body` arrived with its
 * column, was added to the insert's `values`, and was missed in `onConflictDoUpdate`'s `set`. A re-import of
 * a document whose PROSE had changed therefore wrote the new `doc_hash` beside the OLD body, so the row
 * claimed to be current while its content was not — the exact silent drift `doc_hash` exists to make
 * visible. Reproduced on a live database before it was fixed: import a document, edit its body, re-import,
 * and the stored body still read the first version while the hash read the second.
 *
 * A fresh database cannot catch it, because every row goes through INSERT and that list only runs on
 * CONFLICT — which is why the first round-trip proof over 2231 documents passed while the defect stood.
 *
 * Pure: the expectation is DERIVED from the table's own column list rather than restated, so a column added
 * later fails here instead of being silently left out of the mirror.
 */
import { getTableColumns } from "drizzle-orm";
import { describe, expect, it } from "vitest";

import { BOARD_ROW_UPSERT_SET, RUN_EVENT_UPSERT_SET, RUN_UPSERT_SET } from "../../../store/fleet/store.js";
import { boardRowTable } from "../../../store/schema/board.js";
import { runEventTable, runTable } from "../../../store/schema/runs.js";

/**
 * Columns the upsert must NOT name at all, with the reason each is excluded.
 *
 * `id` is the surrogate key and `slug` is the conflict target, so overwriting either would defeat the
 * upsert. `searchable` is generated by the database from `slug` and `summary`, so it cannot be assigned.
 *
 * `importedAt` is deliberately NOT here: it must be PRESENT, set to `now()` rather than copied from the
 * incoming row, which the last case below asserts separately.
 */
const NOT_SETTABLE = new Set(["id", "slug", "searchable"]);

describe("BOARD_ROW_UPSERT_SET", () => {
  it("covers every column a re-import is meant to refresh", () => {
    const expected = Object.keys(getTableColumns(boardRowTable))
      .filter((name) => !NOT_SETTABLE.has(name))
      .toSorted();

    expect(Object.keys(BOARD_ROW_UPSERT_SET).toSorted()).toEqual(expected);
  });

  // The guard over the derived list, per `testing.md`: every assertion above is true of an EMPTY table too.
  it("is checked against a table that really has columns", () => {
    expect(Object.keys(getTableColumns(boardRowTable)).length).toBeGreaterThan(0);
  });

  // The specific column the defect was, named so a regression reads as itself rather than as a count.
  it("refreshes body, the column whose omission wrote a current hash beside stale prose", () => {
    expect(Object.keys(BOARD_ROW_UPSERT_SET)).toContain("body");
  });

  it("does not overwrite the conflict target or the surrogate key", () => {
    expect(Object.keys(BOARD_ROW_UPSERT_SET)).not.toContain("slug");
    expect(Object.keys(BOARD_ROW_UPSERT_SET)).not.toContain("id");
  });

  // importedAt records when THIS store last wrote the row, so copying it from the incoming projection
  // would make it describe the file rather than the write, and a reader could not tell how fresh the row is.
  it("stamps importedAt with the write, rather than copying it from the row", () => {
    // Paired with a key that IS copied, so the absence below is evidence: without this, the case would
    // pass just as happily on a serialisation that never mentions `excluded` for any column.
    expect(JSON.stringify(BOARD_ROW_UPSERT_SET.anchor)).toContain("excluded");
    expect(JSON.stringify(BOARD_ROW_UPSERT_SET.importedAt)).not.toContain("excluded");
  });
});

// The same shape, on the two tables that were NOT the defect. Both were complete when this was written, and
// that is exactly why they are here: a mirror nothing holds in place is one column away from the board's
// failure, and "it happens to be right today" is not a property. Covering only the table that broke would
// fix one instance of a class and leave two more unguarded.
describe("the run upserts are mirrors of their tables too", () => {
  /** `run` upserts on `slug`, so the same three are out of reach there. */
  const RUN_NOT_SETTABLE = new Set(["id", "slug", "searchable"]);
  /** `run_event` upserts on `(run_id, line_number)`, so BOTH halves of that key are the conflict target. */
  const RUN_EVENT_NOT_SETTABLE = new Set(["id", "runId", "lineNumber", "searchable"]);

  it("RUN_UPSERT_SET covers every column a re-fold refreshes", () => {
    const expected = Object.keys(getTableColumns(runTable))
      .filter((name) => !RUN_NOT_SETTABLE.has(name))
      .toSorted();

    expect(Object.keys(RUN_UPSERT_SET).toSorted()).toEqual(expected);
  });

  it("RUN_EVENT_UPSERT_SET covers every column one journal line refreshes", () => {
    const expected = Object.keys(getTableColumns(runEventTable))
      .filter((name) => !RUN_EVENT_NOT_SETTABLE.has(name))
      .toSorted();

    expect(Object.keys(RUN_EVENT_UPSERT_SET).toSorted()).toEqual(expected);
  });

  it("is checked against tables that really have columns", () => {
    expect(Object.keys(getTableColumns(runTable)).length).toBeGreaterThan(0);
    expect(Object.keys(getTableColumns(runEventTable)).length).toBeGreaterThan(0);
  });
});
