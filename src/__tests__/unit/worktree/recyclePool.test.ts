/**
 * The recycle pool: which trees are eligible, that a deposit takes a fixed slot and a full pool declines rather
 * than evicts, that a claim reserves its destination so its rename never replaces anything, that a concurrent
 * claimer can lose an entry without harm, and that an entry installed for another package is thrown away.
 */
import {
  existsSync,
  lstatSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  packageNameOf,
  recycleIdentity,
  stateNamesWorkspace,
  worktreeRecycleIdentity,
} from "../../../worktree/recycleIdentity.js";
import {
  type ClaimSeams,
  claimOrder,
  claimRecycled,
  depositRecycled,
  type PoolEntry,
  productionClaimSeams,
  RECYCLE_POOL_CAPACITY,
} from "../../../worktree/recyclePool.js";
import { discardIntoTrash } from "../../../worktree/trashBatch.js";

/** The head of a real `.yarn-state.yml`, cut to the root workspace entry yarn writes for the project itself. */
const stateFor = ({ name }: { name: string }): string =>
  [
    "# Warning: This file is automatically generated. Removing it is fine, but will",
    "",
    "__metadata:",
    "  version: 1",
    "  nmMode: hardlinks-global",
    "",
    '"left-pad@npm:1.3.0":',
    "  locations:",
    '    - "node_modules/left-pad"',
    "",
    `"${name}@workspace:.":`,
    "  locations:",
    '    - ""',
    "",
  ].join("\n");

let dir = "";

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "recycle-pool-"));
});

afterEach(() => {
  rmSync(dir, { force: true, recursive: true });
});

/** A root `node_modules` yarn installed for `name`, holding one package. */
function installedTree({ at, name }: { at: string; name: string }): string {
  mkdirSync(join(at, "left-pad"), { recursive: true });
  writeFileSync(join(at, ".yarn-state.yml"), stateFor({ name }));
  writeFileSync(join(at, "left-pad", "index.js"), "module.exports = 1;\n");
  return at;
}

/** An `Error` carrying a filesystem `code`, as `node:fs` throws. */
function fsError({ code }: { code: string }): Error {
  return Object.assign(new Error(`${code}: scripted`), { code });
}

describe("packageNameOf", () => {
  it("reads the manifest's name", () => {
    expect(packageNameOf({ manifestText: '{"name":"slopweaver","private":true}' })).toBe("slopweaver");
  });

  it("is undefined for a missing, malformed, nameless or empty-named manifest", () => {
    expect(
      [undefined, "{not json", '{"private":true}', '{"name":""}'].map((manifestText) =>
        packageNameOf({ manifestText }),
      ),
    ).toEqual([undefined, undefined, undefined, undefined]);
  });
});

describe("stateNamesWorkspace", () => {
  it("finds the exact root workspace key", () => {
    expect(stateNamesWorkspace({ packageName: "slopweaver", yarnStateText: stateFor({ name: "slopweaver" }) })).toBe(
      true,
    );
  });

  it("refuses a name that is only a prefix of the installed one", () => {
    expect(stateNamesWorkspace({ packageName: "slop", yarnStateText: stateFor({ name: "slopweaver" }) })).toBe(false);
  });

  it("refuses a state that is not YAML", () => {
    expect(stateNamesWorkspace({ packageName: "slopweaver", yarnStateText: "a: [unclosed" })).toBe(false);
  });
});

describe("recycleIdentity", () => {
  it("is eligible when the state names the manifest's package", () => {
    expect(
      recycleIdentity({ manifestText: '{"name":"slopweaver"}', yarnStateText: stateFor({ name: "slopweaver" }) }),
    ).toEqual({ kind: "eligible", packageName: "slopweaver" });
  });

  it("names each reason a tree is not eligible", () => {
    expect([
      recycleIdentity({ manifestText: undefined, yarnStateText: stateFor({ name: "slopweaver" }) }),
      recycleIdentity({ manifestText: '{"name":"slopweaver"}', yarnStateText: undefined }),
      recycleIdentity({ manifestText: '{"name":"acme-admin"}', yarnStateText: stateFor({ name: "slopweaver" }) }),
    ]).toEqual([
      { detail: "its package.json names no package", kind: "ineligible" },
      { detail: "it carries no readable .yarn-state.yml", kind: "ineligible" },
      { detail: "its .yarn-state.yml was not installed for acme-admin", kind: "ineligible" },
    ]);
  });

  it("reads a worktree off disk", () => {
    writeFileSync(join(dir, "package.json"), '{"name":"slopweaver"}');
    installedTree({ at: join(dir, "node_modules"), name: "slopweaver" });
    expect(worktreeRecycleIdentity({ worktree: dir })).toEqual({ kind: "eligible", packageName: "slopweaver" });
  });
});

describe("claimOrder", () => {
  it("puts the newest first and breaks ties on path", () => {
    const entries: PoolEntry[] = [
      { mtimeMs: 100, path: "/p/0/old", slot: "/p/0" },
      { mtimeMs: 300, path: "/p/2/b", slot: "/p/2" },
      { mtimeMs: 300, path: "/p/1/a", slot: "/p/1" },
    ];
    expect(claimOrder({ entries }).map((entry) => entry.path)).toEqual(["/p/1/a", "/p/2/b", "/p/0/old"]);
  });
});

describe("depositRecycled", () => {
  it("renames the tree into slot 0 of a pool it creates", () => {
    const source = installedTree({ at: join(dir, "nm"), name: "slopweaver" });
    const pool = join(dir, "pool");
    expect(depositRecycled({ entryName: "wt-1", pool, source })).toEqual({
      kind: "deposited",
      to: join(pool, "0", "wt-1"),
    });
    expect([existsSync(source), existsSync(join(pool, "0", "wt-1", "left-pad", "index.js"))]).toEqual([false, true]);
  });

  it("takes the first free slot, skipping a taken one", () => {
    const pool = join(dir, "pool");
    mkdirSync(join(pool, "0"), { recursive: true });
    const source = installedTree({ at: join(dir, "nm"), name: "slopweaver" });
    expect(depositRecycled({ entryName: "wt-2", pool, source })).toEqual({
      kind: "deposited",
      to: join(pool, "1", "wt-2"),
    });
  });

  it("declines a full pool and leaves the tree where it was", () => {
    const pool = join(dir, "pool");
    for (let index = 0; index < RECYCLE_POOL_CAPACITY; index += 1) {
      mkdirSync(join(pool, String(index)), { recursive: true });
    }
    const source = installedTree({ at: join(dir, "nm"), name: "slopweaver" });
    expect(depositRecycled({ entryName: "wt-3", pool, source })).toEqual({
      detail: "all 4 slots hold a tree",
      kind: "declined",
      reason: "pool-full",
    });
    expect(existsSync(join(source, ".yarn-state.yml"))).toBe(true);
  });

  it("declines a symlink rather than following it", () => {
    const real = installedTree({ at: join(dir, "real"), name: "slopweaver" });
    const link = join(dir, "link");
    symlinkSync(real, link);
    expect(depositRecycled({ entryName: "wt-4", pool: join(dir, "pool"), source: link })).toEqual({
      detail: `${link} is not a real directory`,
      kind: "declined",
      reason: "not-recyclable",
    });
  });

  it("gives the slot back when the rename fails", () => {
    // A directory cannot be renamed into its own subtree, so this rename fails EINVAL after the slot was taken.
    const source = installedTree({ at: join(dir, "nm"), name: "slopweaver" });
    const pool = join(source, "pool");
    expect(depositRecycled({ entryName: "wt-5", pool, source })).toEqual({
      detail: "the rename into the pool failed (EINVAL)",
      kind: "declined",
      reason: "rename-failed",
    });
    expect(readdirSync(pool)).toEqual([]);
  });
});

/** Scripted seams: the pool's entries, which renames throw, and a record of every call. */
function scripted({
  entries,
  states = {},
  renameFails = {},
  reserveFails,
}: {
  entries: readonly PoolEntry[];
  states?: Readonly<Record<string, string>>;
  renameFails?: Readonly<Record<string, string>>;
  reserveFails?: string;
}): { seams: ClaimSeams; calls: string[] } {
  const calls: string[] = [];
  const seams: ClaimSeams = {
    discard: ({ dir: discarded }) => {
      calls.push(`discard ${discarded}`);
      return undefined;
    },
    entries: () => entries,
    read: ({ path }) => states[path],
    release: ({ path }) => {
      calls.push(`release ${path}`);
    },
    rename: ({ from, to }) => {
      calls.push(`rename ${from} -> ${to}`);
      const code = renameFails[from];
      if (code !== undefined) {
        throw fsError({ code });
      }
    },
    reserve: ({ path }) => {
      calls.push(`reserve ${path}`);
      if (reserveFails !== undefined) {
        throw fsError({ code: reserveFails });
      }
    },
  };
  return { calls, seams };
}

const NEW: PoolEntry = { mtimeMs: 200, path: "/pool/1/new", slot: "/pool/1" };
const OLD: PoolEntry = { mtimeMs: 100, path: "/pool/0/old", slot: "/pool/0" };
const FITS = stateFor({ name: "slopweaver" });

describe("claimRecycled", () => {
  it("reserves the destination, renames the newest entry over its own reservation, then frees the slot", () => {
    const { seams, calls } = scripted({
      entries: [OLD, NEW],
      states: { "/pool/0/old/.yarn-state.yml": FITS, "/pool/1/new/.yarn-state.yml": FITS },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      from: "/pool/1/new",
      kind: "claimed",
    });
    expect(calls).toEqual(["reserve /w/node_modules", "rename /pool/1/new -> /w/node_modules", "release /pool/1"]);
  });

  it("reports an empty pool without reserving anything", () => {
    const { seams, calls } = scripted({ entries: [] });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "the recycle pool is empty",
      kind: "skipped",
      reason: "pool-empty",
    });
    expect(calls).toEqual([]);
  });

  it("touches nothing when the destination already exists", () => {
    const { seams, calls } = scripted({
      entries: [NEW],
      reserveFails: "EEXIST",
      states: { "/pool/1/new/.yarn-state.yml": FITS },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "this worktree already has a node_modules",
      kind: "skipped",
      reason: "destination-present",
    });
    expect(calls).toEqual(["reserve /w/node_modules"]);
  });

  it("moves on when a concurrent claimer took the newest entry first", () => {
    const { seams, calls } = scripted({
      entries: [OLD, NEW],
      renameFails: { "/pool/1/new": "ENOENT" },
      states: { "/pool/0/old/.yarn-state.yml": FITS, "/pool/1/new/.yarn-state.yml": FITS },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      from: "/pool/0/old",
      kind: "claimed",
    });
    expect(calls).toEqual([
      "reserve /w/node_modules",
      "rename /pool/1/new -> /w/node_modules",
      "rename /pool/0/old -> /w/node_modules",
      "release /pool/0",
    ]);
  });

  it("stops without retrying when something was written into its reservation, and releases it", () => {
    const { seams, calls } = scripted({
      entries: [OLD, NEW],
      renameFails: { "/pool/1/new": "ENOTEMPTY" },
      states: { "/pool/0/old/.yarn-state.yml": FITS, "/pool/1/new/.yarn-state.yml": FITS },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "claiming /pool/1/new failed (ENOTEMPTY): something was written into the reservation",
      kind: "skipped",
      reason: "destination-present",
    });
    expect(calls).toEqual([
      "reserve /w/node_modules",
      "rename /pool/1/new -> /w/node_modules",
      "release /w/node_modules",
    ]);
  });

  it("stops on a cross-volume rename rather than copying", () => {
    const { seams } = scripted({
      entries: [NEW],
      renameFails: { "/pool/1/new": "EXDEV" },
      states: { "/pool/1/new/.yarn-state.yml": FITS },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "claiming /pool/1/new failed (EXDEV)",
      kind: "skipped",
      reason: "cross-device",
    });
  });

  it("discards an entry installed for another package from the pool and claims the next", () => {
    const { seams, calls } = scripted({
      entries: [OLD, NEW],
      states: { "/pool/0/old/.yarn-state.yml": FITS, "/pool/1/new/.yarn-state.yml": stateFor({ name: "acme-admin" }) },
    });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      from: "/pool/0/old",
      kind: "claimed",
    });
    expect(calls).toEqual([
      "reserve /w/node_modules",
      "discard /pool/1/new",
      "release /pool/1",
      "rename /pool/0/old -> /w/node_modules",
      "release /pool/0",
    ]);
  });

  it("reads an entry whose state has vanished as taken by another claimer", () => {
    const { seams } = scripted({ entries: [NEW] });
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "/pool/1/new was claimed by another provision",
      kind: "skipped",
      reason: "contended",
    });
  });

  it("reports a pool it cannot read", () => {
    const seams: ClaimSeams = {
      ...scripted({ entries: [] }).seams,
      entries: () => {
        throw fsError({ code: "EACCES" });
      },
    };
    expect(claimRecycled({ destination: "/w/node_modules", packageName: "slopweaver", pool: "/pool", seams })).toEqual({
      detail: "the pool could not be read (EACCES)",
      kind: "skipped",
      reason: "pool-unreadable",
    });
  });
});

describe("claimRecycled on the real filesystem", () => {
  /** Production seams discarding into a trash under the test directory. */
  const realSeams = (): ClaimSeams =>
    productionClaimSeams({
      discard: ({ dir: discarded }) =>
        discardIntoTrash({ dir: discarded, label: "wt", nowMs: 7, trashDir: join(dir, "trash") }),
    });

  it("deposits then claims a tree whole, leaving the pool empty", () => {
    const pool = join(dir, "pool");
    depositRecycled({ entryName: "a", pool, source: installedTree({ at: join(dir, "nm"), name: "slopweaver" }) });
    const destination = join(dir, "w", "node_modules");
    mkdirSync(join(dir, "w"));
    expect(claimRecycled({ destination, packageName: "slopweaver", pool, seams: realSeams() })).toEqual({
      from: join(pool, "0", "a"),
      kind: "claimed",
    });
    expect([existsSync(join(destination, "left-pad", "index.js")), readdirSync(pool)]).toEqual([true, []]);
  });

  it("never replaces a symlink already at the destination", () => {
    const pool = join(dir, "pool");
    depositRecycled({ entryName: "a", pool, source: installedTree({ at: join(dir, "nm"), name: "slopweaver" }) });
    mkdirSync(join(dir, "w"));
    const destination = join(dir, "w", "node_modules");
    symlinkSync(join(dir, "shared"), destination);
    expect(claimRecycled({ destination, packageName: "slopweaver", pool, seams: realSeams() }).kind).toBe("skipped");
    expect([lstatSync(destination).isSymbolicLink(), existsSync(join(pool, "0", "a", ".yarn-state.yml"))]).toEqual([
      true,
      true,
    ]);
  });

  it("never replaces an empty directory already at the destination, and leaves it in place", () => {
    const pool = join(dir, "pool");
    depositRecycled({ entryName: "a", pool, source: installedTree({ at: join(dir, "nm"), name: "slopweaver" }) });
    const destination = join(dir, "w", "node_modules");
    mkdirSync(destination, { recursive: true });
    expect(claimRecycled({ destination, packageName: "slopweaver", pool, seams: realSeams() }).kind).toBe("skipped");
    expect([readdirSync(destination), existsSync(join(pool, "0", "a", ".yarn-state.yml"))]).toEqual([[], true]);
  });

  it("throws a foreign entry into a trash batch and frees its slot", () => {
    const pool = join(dir, "pool");
    depositRecycled({ entryName: "a", pool, source: installedTree({ at: join(dir, "nm"), name: "acme-admin" }) });
    mkdirSync(join(dir, "w"));
    const destination = join(dir, "w", "node_modules");
    expect(claimRecycled({ destination, packageName: "slopweaver", pool, seams: realSeams() }).kind).toBe("skipped");
    const batch = join(dir, "trash", `wt-7-${String(process.pid)}`);
    expect([
      existsSync(join(batch, "0", ".yarn-state.yml")),
      existsSync(join(batch, "pending.json")),
      readdirSync(pool),
      existsSync(destination),
    ]).toEqual([true, false, [], false]);
  });
});
