/** Provenance for one stored entity; the console kinds name the console surface and carry a screenshot. */
function sourceFor({ kind }: { kind: CrowdstrikeKind }): CrowdstrikeEntity["source"] {
  const isConsole = kind === "console-page" || kind === "console-request";
  return {
    artifacts: isConsole
      ? [
          {
            byteLength: 2048,
            kind: "page-png",
            mediaType: "image/png",
            relativePath: `artifacts/${kind}.png`,
            sha256: "a".repeat(64),
          },
        ]
      : [],
    deepLink: `https://falcon.example-cloud.test/${kind}`,
    deepLinkStatus: isConsole ? "browser-discovered" : "provider-provided",
    endpoint: `/example/${kind}`,
    observedAt: SEEN,
    surface: isConsole ? "falcon-console" : "falcon-api",
  };
}

