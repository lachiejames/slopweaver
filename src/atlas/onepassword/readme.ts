/**
 * The README this atlas writes into its own directory, and why one exists here and nowhere else.
 *
 * Anyone who finds `~/.slopweaver/atlas/onepassword/` on a laptop is entitled to know, without reading any
 * source, exactly what a directory named after a password manager contains. The answer is "no secrets, and
 * here is the list", and it belongs beside the files rather than in a repository they may never see.
 *
 * It is GENERATED rather than hand-written on purpose: the two lists below are derived from
 * `descriptor.ts`, `inventory.ts` and `sensitivity.ts` — the same constants the code enforces — so a README
 * that disagrees with the gate cannot be produced. A hand-written one would be true on the day it was
 * written and confidently wrong thereafter, which is the exact failure a document like this must not have.
 */
import { ONEPASSWORD_ATLAS_DESCRIPTOR } from "./descriptor.js";
import {
  ONEPASSWORD_FORBIDDEN_OP_VERBS,
  ONEPASSWORD_OP_COMMANDS,
  ONEPASSWORD_OUT_OF_SCOPE_GROUPS,
} from "./inventory.js";
import { ONEPASSWORD_KINDS } from "./model.js";

/** The filename, relative to the atlas directory. */
export const ONEPASSWORD_README_FILENAME = "README.md";

/**
 * Render the atlas README from the same constants the code enforces.
 *
 * @param at the ISO timestamp of the generation this README describes
 * @returns the README's full text, newline-terminated
 */
// Splitting this into per-section helpers would hide the README's reading order behind six function names
// and let two sections contradict each other; the lists that could actually drift are already generated
// from the constants the code enforces.
// max-lines-exempt: one document, rendered as one flat array of its own lines
export function renderOnepasswordReadme({ at }: { at: string }): string {
  const lines = [
    "# The 1Password atlas — what is in here, and what is deliberately not",
    "",
    "A local, read-only map of a 1Password account's ADMINISTRATIVE shape: who is in it, which groups and",
    "vaults exist, who can reach which vault, how much each vault holds, and what administrative activity",
    "has happened.",
    "",
    "**No secret from any 1Password item is stored here.** That is enforced by three independent mechanisms",
    "in the code that writes these files, not by anybody's care — see the bottom of this page.",
    "",
    `Generated by \`${ONEPASSWORD_ATLAS_DESCRIPTOR.resyncCommand}\`. This generation: ${at}.`,
    "",
    "## What IS stored",
    "",
    ...ONEPASSWORD_KINDS.map((kind) => `- \`${kind}\``),
    "",
    "Every record carries where it came from, when it was seen, and — where one exists — the exact console",
    "URL a human opens to see the same thing.",
    "",
    "## What is NOT stored, ever",
    "",
    ...ONEPASSWORD_ATLAS_DESCRIPTOR.excludes.map((entry) => `- ${entry.because} (${entry.ground})`),
    "",
    "Also out of scope, for reasons that are about usefulness rather than sensitivity:",
    "",
    ...ONEPASSWORD_OUT_OF_SCOPE_GROUPS.map((entry) => `- ${entry}`),
    "",
    "## Every call this atlas is capable of making",
    "",
    "This is the complete list. It is a closed allowlist in the source, not a summary of current usage:",
    "",
    "```",
    ...ONEPASSWORD_OP_COMMANDS.map((command) => `op ${command.template.join(" ")} --format=json`),
    "POST https://<events-host>/api/v2/auditevents",
    "```",
    "",
    `Every verb is a read. The verbs that would return an item's contents — ${ONEPASSWORD_FORBIDDEN_OP_VERBS.map((verb) => `\`op ${verb}\``).join(", ")}`,
    "— are absent from that list and a test fails if one is added to it.",
    "",
    "## The three mechanisms",
    "",
    "1. **A closed command allowlist** (`src/atlas/onepassword/inventory.ts`). Nothing can request an argv;",
    "   a caller names a surface and the argv is looked up. The item-reading verbs are not in the table.",
    "2. **An allowlist projection** (`src/atlas/onepassword/model.ts`). Provider JSON is parsed through a",
    "   schema naming every field kept, so an unrecognised field is dropped at the boundary rather than",
    "   stored because nobody thought to exclude it.",
    "3. **A pre-write sensitivity gate** (`src/atlas/onepassword/sensitivity.ts`). Every document is scanned",
    "   immediately before it is written; a forbidden key name or a credential-shaped value REFUSES the",
    "   whole publish rather than redacting it, so nothing half-written is left behind.",
    "",
    "## The one thing that is reported rather than refused",
    "",
    "The private hygiene denylist at `$SLOPWEAVER_HOME/hygiene-denylist.txt` is run over every document and",
    "each hit is recorded as a `sensitivity-gate-reported` gap — but it does not refuse the write. That",
    "denylist exists to keep organisation-specific words out of the git repository, and this atlas's entire",
    "subject is that organisation: its people, its groups, its vault names. Refusing on those words would",
    "only ever admit an empty atlas.",
    "",
    "## Reading it",
    "",
    "One JSON file per kind, keys sorted, so `grep` and `jq` both work. `manifest.json` is the authority on",
    "what was published and is written last. Nothing here is refreshed automatically — it is as current as",
    `the last \`${ONEPASSWORD_ATLAS_DESCRIPTOR.resyncCommand}\`.`,
    "",
  ];
  return `${lines.join("\n")}\n`;
}
