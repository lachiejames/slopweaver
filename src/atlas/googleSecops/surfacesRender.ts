/**
 * The exact text of the two generated modules — `generated/surfaces.ts` and `generated/protoLock.ts`, the
 * whole of `generated/` — for a set of values: the one renderer the generator writes with and both checks
 * compare against.
 *
 * Why the comparison is the check rather than only the digest: the digest hashes values READ off the
 * imports, and a hand-edited module can make a read lie — a `toJSON` member, an array whose own
 * `Symbol.iterator` yields another list, a getter, a Proxy, a side effect after import that rewrites a
 * sibling. Adversarial reviews built four of those, and every check without the pinned bytes passed (the
 * pins ones passed `--spec-dir` too). Each is CODE, and this renderer emits only type imports and JSON
 * literals, so a committed file byte-equal to `render(its own imports)` cannot carry any of them: whatever
 * the import produced, the file is literal data. Every module the two import is a type, erased before
 * anything runs. Elements are read by index (`map`), never through an array's iterator.
 */
import type { GoogleSecopsInventoryCensus, GoogleSecopsUnpublishedService } from "./inventory.js";
import type { GoogleSecopsPin } from "./pin.js";
import type { GoogleSecopsSurfaceRow } from "./surfaceRow.js";

/** The surfaces module header, ending at the opening bracket of the rows array. */
const SURFACES_HEADER = [
  "/**",
  " * The closed inventory of every method the Chronicle (Google SecOps) v1 API publishes.",
  " *",
  " * GENERATED by `tools/generateGoogleSecopsSurfaces.ts` from the googleapis files pinned in `protoLock.ts`.",
  " * Do not edit: a hand-edited row is a row no census caught, and the unit lane re-checks every count.",
  " *",
  " * The row TYPE and its field meanings are `../surfaceRow.ts`; the disposition rules are",
  " * `../dispositions.ts`; which services are rows at all is `../inventory.ts`.",
  " */",
  'import type { GoogleSecopsSurfaceRow } from "../surfaceRow.js";',
  "",
  "/**",
  " * Every published Chronicle v1 method, sorted by id.",
  " * @internal",
  " */",
  "export const GOOGLE_SECOPS_SURFACES: readonly GoogleSecopsSurfaceRow[] = [",
].join("\n");

/** The lock module header, ending before the first export. */
const LOCK_HEADER = [
  "/**",
  " * The Chronicle v1 inventory's pin: the googleapis commit, the source files, the unpublished services,",
  " * the inventory digest and the census. What each one means, and how to move the pin, is `../pin.ts`.",
  " *",
  " * GENERATED by `tools/generateGoogleSecopsSurfaces.ts`, and required byte-equal to what it renders for",
  " * its own imports. Edit the commit and the pins by hand only to move the pin, then regenerate.",
  " */",
  'import type { GoogleSecopsInventoryCensus, GoogleSecopsUnpublishedService } from "../inventory.js";',
  'import type { GoogleSecopsPin } from "../pin.js";',
].join("\n");

/**
 * Render a list as one JSON literal per line, read by index.
 *
 * @param items the elements to render
 * @returns the lines between the brackets
 */
function literalLines({ items }: { items: readonly unknown[] }): string {
  return items.map((item) => `  ${JSON.stringify(item)},`).join("\n");
}

/**
 * Render the rows as the committed module.
 *
 * @param rows the compiled inventory's rows, already sorted by id
 * @returns the module text
 */
export function renderGoogleSecopsSurfaces({ rows }: { rows: readonly GoogleSecopsSurfaceRow[] }): string {
  return `${SURFACES_HEADER}\n${literalLines({ items: rows })}\n];\n`;
}

/**
 * Render the pin as the committed lock module.
 *
 * @param commit the googleapis commit every pinned document is read at
 * @param pins every pinned file, in lock order
 * @param unpublished the declared-but-unpublished services, sorted by name
 * @param digest the inventory digest (`tableIntegrity.ts`)
 * @param census every count the committed table must hold
 * @returns the module text
 */
export function renderGoogleSecopsLock({
  commit,
  pins,
  unpublished,
  digest,
  census,
}: {
  commit: string;
  pins: readonly GoogleSecopsPin[];
  unpublished: readonly GoogleSecopsUnpublishedService[];
  digest: string;
  census: GoogleSecopsInventoryCensus;
}): string {
  return [
    LOCK_HEADER,
    "",
    "/** The googleapis commit every pinned document is read at. */",
    `export const GOOGLE_SECOPS_PROTO_COMMIT = ${JSON.stringify(commit)};`,
    "",
    "/** @internal */",
    "export const GOOGLE_SECOPS_PINS: readonly GoogleSecopsPin[] = [",
    literalLines({ items: pins }),
    "];",
    "",
    "export const GOOGLE_SECOPS_UNPUBLISHED_SERVICES: readonly GoogleSecopsUnpublishedService[] = [",
    literalLines({ items: unpublished }),
    "];",
    "",
    `export const GOOGLE_SECOPS_INVENTORY_SHA256 = ${JSON.stringify(digest)};`,
    "",
    `export const GOOGLE_SECOPS_INVENTORY_CENSUS: GoogleSecopsInventoryCensus = ${JSON.stringify(census)};`,
    "",
  ].join("\n");
}
