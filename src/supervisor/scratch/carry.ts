/**
 * The pure half of `slopweaver supervisor scratch-carry`: the retention rule for what one supervisor seat's
 * scratch directory hands to the next.
 *
 * Every seat used to boot with `rsync -a handoff-<n-1>/ handoff-<n>/`, carrying everything — over ten thousand files
 * and hundreds of MB in one seat's directory, tens of GB across well over a hundred seat directories. Re-measure with
 * `du -sh ~/.slopweaver/supervisor-scratch; ls -d ~/.slopweaver/supervisor-scratch/handoff-* | wc -l`. Almost
 * all of it was per-tick readings a successor never reads again, and the rest was the scripts that produced
 * them, which is how one seat's `tick.sh` reached the next.
 *
 * The rule is an ALLOWLIST, so a seat inherits state and nothing else:
 *
 * - `form.json` — the briefing form every sweep edits through the `briefing` verbs;
 * - `open-pages.json` — the open-pages ledger the render reads;
 * - `shell.txt` — the page shell the local briefing is written inside.
 *
 * A reading is retaken by `supervisor tick-capture`; `run.json` and `autonomy-qualified.jsonl` are
 * regenerated by `supervisor refresh-run`; a script is never inherited at all. Something a successor needs
 * that is not on this list is a change to this list, reviewed — never a hand copy.
 *
 * No I/O.
 */

/** The files a seat inherits from its predecessor, in the order they are copied. */
export const CARRIED_FILES = ["form.json", "open-pages.json", "shell.txt"] as const;

/**
 * What happened, or would happen, to one inherited file.
 *
 * @internal — named by {@link CarryReport}; nothing outside this module constructs one.
 */
export interface CarriedFile {
  readonly name: string;
  /** `carried` copied (or would be, under `--dry-run`); `absent` the predecessor never had it. */
  readonly status: "carried" | "absent";
  readonly bytes: number;
}

/** A carry's whole report — the document `--json` prints. */
export interface CarryReport {
  readonly from: string;
  readonly to: string;
  readonly dryRun: boolean;
  readonly files: readonly CarriedFile[];
  /** Top-level entries in the predecessor's directory that were NOT carried. */
  readonly leftBehind: { readonly entries: number; readonly bytes: number };
}

/**
 * One top-level entry of the predecessor's directory.
 *
 * @internal — read by this module, its verb and its own tests.
 */
export interface ScratchEntry {
  readonly name: string;
  /** A regular file's size; a directory counts as zero here, since the carry never descends. */
  readonly bytes: number;
}

/**
 * Decide what a carry does, from the predecessor's top-level entries.
 *
 * @param from the predecessor's directory
 * @param to the successor's directory
 * @param dryRun whether the carry only reports
 * @param entries the predecessor's top-level entries
 * @returns the report the verb prints, before or instead of copying
 */
export function planCarry({
  from,
  to,
  dryRun,
  entries,
}: {
  from: string;
  to: string;
  dryRun: boolean;
  entries: readonly ScratchEntry[];
}): CarryReport {
  const carried = new Set<string>(CARRIED_FILES);
  const files = CARRIED_FILES.map((name): CarriedFile => {
    const entry = entries.find((candidate) => candidate.name === name);
    if (entry === undefined) {
      return { bytes: 0, name, status: "absent" };
    }
    return { bytes: entry.bytes, name, status: "carried" };
  });
  const behind = entries.filter((entry) => !carried.has(entry.name));
  return {
    dryRun,
    files,
    from,
    leftBehind: { bytes: behind.reduce((sum, entry) => sum + entry.bytes, 0), entries: behind.length },
    to,
  };
}

/**
 * The human lines for a carry report.
 *
 * @returns the lines to print
 */
export function carrySummaryLines({ report }: { report: CarryReport }): readonly string[] {
  const verb = report.dryRun ? "would carry" : "carried";
  const carried = report.files.filter((file) => file.status === "carried");
  const absent = report.files.filter((file) => file.status === "absent");
  const megabytes = (report.leftBehind.bytes / (1024 * 1024)).toFixed(1);
  return [
    `supervisor scratch-carry: ${verb} ${String(carried.length)} of ${String(report.files.length)} inherited ` +
      `files from ${report.from} to ${report.to}`,
    ...carried.map((file) => `  ${file.name} (${String(file.bytes)} bytes)`),
    ...absent.map((file) => `  ${file.name}: absent in the predecessor — nothing to inherit`),
    `  left behind: ${String(report.leftBehind.entries)} top-level entries, ${megabytes} MiB of top-level files ` +
      "— readings are retaken by tick-capture, run.json by refresh-run, and a script is never inherited",
  ];
}
