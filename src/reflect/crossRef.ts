/**
 * TIER 2 — the cross-reference. Three questions asked of every finding, and none of them is ever itself a
 * source of one.
 *
 * **Is this already covered?** The board is the only register of what is in flight, and a proposal that
 * duplicates an open doc costs the owner the whole read before they can say "already planned". The
 * measurement that makes this non-optional rather than a nicety: on the V1 pass, ALREADY-DONE accounted for
 * 41% of all walk friction — the single dominant failure mode, larger than every wrong finding combined.
 *
 * **Is this already known?** A friction recurring DESPITE an existing memory is a STRONGER finding, not a
 * duplicate. The memory did not reach the point of use, which is a defect in how the knowledge is delivered
 * rather than an absence of knowledge, and it is invisible to anyone reading either the memory or the
 * friction alone.
 *
 * **Has this already been refuted?** `docs/recurring-failure-register.md` records every failure class an
 * adversarial pass examined and KILLED, with the reason — several because a gate already refuses them. That
 * register exists so a 29-day transcript mining pass is never repeated, and re-proposing one
 * of its dead classes is the exact waste it was written to prevent. Nobody should have to fan out over old
 * transcripts again to rederive friction points, because the self-improvement loop runs every 24 hours and
 * catches future ones — this function is the half that makes the register load-bearing rather than a doc
 * nobody opens.
 *
 * So coverage DEMOTES and knowledge PROMOTES, and neither removes. A hand-run ranked a boarded
 * finding SECOND of eight — "biggest raw impact; ranked below the first only because the board holds it" —
 * which is exactly a demotion and exactly not a deletion. A refutation demotes for the same reason and
 * removes for the same reason: it can go stale, so it is printed rather than obeyed.
 *
 * ## The match is RARE-token overlap, and it now lives in `#lib/rareTokens.js`
 *
 * No model runs here, so a match is vocabulary overlap, and plain overlap is useless — the measurement that
 * says so, and the document-frequency ceiling that answers it, moved to `lib/rareTokens.ts` when
 * `memory/hygiene/` needed the same question answered. Read that file for why rarity is the mechanism; this
 * one only decides what to do with an answer.
 *
 * The subject side is the finding's class key and locus, never its summary: the summary is prose this
 * program generated, so its vocabulary describes the renderer rather than the friction.
 *
 * Conservative in both directions, and missing is the safe one: a missed match surfaces a finding the owner
 * can dismiss in one word, while a false match silently demotes a real finding and the owner never learns it
 * existed.
 */
import { join } from "node:path";

import {
  COVERAGE_TOKEN_MATCHES,
  type CoverageSource,
  distinctiveTokens,
  indexSources,
  sharedRareTokens,
} from "#lib/rareTokens.js";
import { clampDial, type FrictionFinding } from "./finding.js";
import { loadRegister } from "./registerPages.js";
import type { SubstrateReader } from "./substrate.js";

/**
 * Which sources share enough RARE vocabulary with a finding to be about the same subject.
 *
 * The subject is the finding's class key and locus. Its summary is deliberately excluded — that string is
 * generated by this program, so matching on it measures the renderer's vocabulary rather than the friction's.
 * That choice is the only thing this adds over calling `#lib/rareTokens.js` directly, and it is why it is a
 * function rather than an inline call: a caller passing the summary in by mistake would get a plausible answer.
 *
 * @param finding the finding to place
 * @param sources the board docs or memories to place it against
 * @param minimum how many rare tokens must be shared
 * @returns the ids of every source that matched, in the order they were given
 */
export function matchingSources({
  finding,
  sources,
  minimum = COVERAGE_TOKEN_MATCHES,
}: {
  finding: FrictionFinding;
  sources: readonly CoverageSource[];
  minimum?: number;
}): readonly string[] {
  const subject = distinctiveTokens({ text: `${finding.classKey} ${finding.locus}` });
  const index = indexSources({ sources });
  return sources.flatMap((source, position) => {
    // Safe: `indexSources` returns one token set per source, index-aligned.
    const theirs = index.tokens[position]!;
    const shared = sharedRareTokens({ source: theirs, subject, tooCommon: index.tooCommon });
    return shared >= minimum ? [source.id] : [];
  });
}

/** How much a finding the board already covers is demoted. One step, never a removal. */
export const COVERED_IMPACT_STEP = -1;

/** How much a finding that recurs despite an existing memory is promoted. */
export const KNOWN_IMPACT_STEP = 1;

/**
 * How much a finding the register already refuted is demoted.
 *
 * The SAME step as {@link COVERED_IMPACT_STEP}, deliberately, and not a larger one invented for the
 * occasion. A stronger demotion is arguable — a refuted class was examined and killed, where a boarded doc
 * merely exists — but nothing here has measured that difference, and this file's constants are measured
 * ones. The value of the annotation is the REASON it prints, not a bigger number.
 */
export const REFUTED_IMPACT_STEP = COVERED_IMPACT_STEP;

/**
 * Annotate every finding with what already covers it, what already knows it, and what has already been
 * refuted about it, and move its impact.
 *
 * Pure. The class key is untouched, so a finding's identity — and therefore its recurrence counter and any
 * terminal drop — is unaffected by whether the board happened to hold a doc that day.
 *
 * @param findings everything the collectors returned
 * @param board the open board docs to check coverage against
 * @param memory the memory corpus to check knowledge against
 * @param refuted the register's refuted classes, so a dead one is not re-proposed as new
 * @returns the same findings, annotated, with impact moved by what was found
 */
export function crossReference({
  findings,
  board,
  memory,
  refuted = [],
}: {
  findings: readonly FrictionFinding[];
  board: readonly CoverageSource[];
  memory: readonly CoverageSource[];
  refuted?: readonly CoverageSource[];
}): readonly FrictionFinding[] {
  return findings.map((finding) => {
    const coveredBy = matchingSources({ finding, sources: board });
    const knownBy = matchingSources({ finding, sources: memory });
    const refutedBy = matchingSources({ finding, sources: refuted });
    const moved =
      finding.impact +
      (coveredBy.length > 0 ? COVERED_IMPACT_STEP : 0) +
      (knownBy.length > 0 ? KNOWN_IMPACT_STEP : 0) +
      (refutedBy.length > 0 ? REFUTED_IMPACT_STEP : 0);
    return { ...finding, coveredBy, impact: clampDial({ value: moved }), knownBy, refutedBy };
  });
}

/**
 * How many characters of a doc or memory are read for matching — its name, its front matter and its
 * opening. Never the body: a whole doc's vocabulary is broad enough to match anything, which is the same
 * failure the document-frequency ceiling exists to close, reached from the other side.
 *
 * @internal
 */
export const COVERAGE_TEXT_BYTES = 600;

/**
 * Read the open board docs as coverage sources.
 *
 * Deliberately does NOT use `scanBoard`: that parses front-matter, resolves probes and reads the whole doc,
 * which is the right thing for the board's own gates and far more than a token match needs. Here a doc is a
 * name and its opening bytes, read through the same injected seam as every substrate, so this pass stays a
 * cheap local read over a directory of markdown.
 *
 * @param handoverDir the directory holding the orchestration docs
 * @param reader the filesystem seam
 * @returns one source per readable doc
 */
export function readBoardCoverage({
  handoverDir,
  reader,
}: {
  handoverDir: string;
  reader: SubstrateReader;
}): readonly CoverageSource[] {
  return reader
    .listNames(handoverDir)
    .filter((name) => name.endsWith(".md"))
    .toSorted((a, b) => a.localeCompare(b))
    .flatMap((name) => {
      const text = reader.readText(join(handoverDir, name));
      return text === undefined
        ? []
        : [{ id: name.slice(0, -".md".length), text: `${name} ${text.slice(0, COVERAGE_TEXT_BYTES)}` }];
    });
}

/**
 * Find every memory corpus under the harness's project directories.
 *
 * SEARCHED rather than reconstructed from a mangled cwd, for the reason `sessions/liveSessionStore.ts` already
 * states about transcripts: a wrong guess at the mangled name yields an empty answer, which reads as "no
 * memory exists" rather than as a bug. Every project's memories count, not just this checkout's — knowledge
 * recorded while working on another repository still means the knowledge exists and is not reaching the
 * point of use.
 *
 * @param projectsDir the harness's `projects` directory
 * @param reader the filesystem seam
 * @returns every directory that holds a memory corpus, sorted
 */
export function discoverMemoryDirs({
  projectsDir,
  reader,
}: {
  projectsDir: string;
  reader: SubstrateReader;
}): readonly string[] {
  return reader
    .listNames(projectsDir)
    .toSorted((a, b) => a.localeCompare(b))
    .map((project) => join(projectsDir, project, "memory"))
    .filter((dir) => reader.listNames(dir).length > 0);
}

/**
 * Read the memory corpus as knowledge sources.
 *
 * The index file is skipped: it is one line per memory, so matching against it would match everything at
 * once and report the whole corpus as knowing every finding.
 *
 * @param memoryDir the Claude Code auto-memory directory for this project
 * @param reader the filesystem seam
 * @returns one source per readable memory
 */
export function readMemoryCoverage({
  memoryDir,
  reader,
}: {
  memoryDir: string;
  reader: SubstrateReader;
}): readonly CoverageSource[] {
  return reader
    .listNames(memoryDir)
    .filter((name) => name.endsWith(".md") && name !== "MEMORY.md" && !name.startsWith("INDEX-"))
    .toSorted((a, b) => a.localeCompare(b))
    .flatMap((name) => {
      const text = reader.readText(join(memoryDir, name));
      return text === undefined
        ? []
        : [{ id: name.slice(0, -".md".length), text: `${name} ${text.slice(0, COVERAGE_TEXT_BYTES)}` }];
    });
}

/**
 * Read the recurring-failure register's REFUTED classes as coverage sources.
 *
 * ## Why this is parsed out of a markdown doc rather than held as data
 *
 * The register is committed prose because it is what a HUMAN reads before proposing a gate, and a second
 * machine-readable copy is a second thing to keep true. A register that has drifted out of shape yields NO
 * sources rather than wrong ones — the same missing-is-safe direction the rest of this file takes.
 *
 * Only the REFUTED section is read HERE, and that is this function's scope rather than the register's. The
 * survivors are live build candidates; a finding that matches one of those is a finding the register AGREES
 * with, and demoting it would bury exactly the evidence that says the class is real. The live half is read
 * by `../devLint/registerBindings.ts`, through the same parser — that split is the point of
 * `./registerDoc.ts` existing, since this function reading only Refuted is what let three Survivor
 * rows stay false for six days with nothing to notice. A page that is missing is kept missing-is-safe here:
 * the pages that did read still count, and an absent Refuted page means no refutations to match. A page read
 * with a problem — the wrong opening, a section it is not listed as holding — yields nothing either, since a
 * class read off it may sit in the wrong section, and a live class matched as refuted would bury it.
 *
 * @param registerPath the committed register's parent page, `docs/recurring-failure-register.md`; its child
 *   pages resolve beside it
 * @param reader the filesystem seam
 * @returns one source per refuted class — its name, matched against its own name plus the refutation reason
 */
export function readRegisterCoverage({
  registerPath,
  reader,
}: {
  registerPath: string;
  reader: SubstrateReader;
}): readonly CoverageSource[] {
  const register = loadRegister({ parentPath: registerPath, reader });
  return (
    register.doc.classes
      .filter((one) => one.section === "refuted" && !register.unread.includes(one.path))
      // A row that lost its reason cell is a malformed row, not a class with an empty reason: drop it rather
      // than emit a source whose match text is only the name it already carries.
      .filter((one) => one.reason.length > 0)
      .map((one) => ({ id: one.name, text: `${one.name} ${one.reason}` }))
  );
}
