/**
 * The one rule about a PUBLISH claim: a line saying a page was published or something is up to date names
 * where the owner goes to see it.
 *
 * Every time the supervisor says a page was published or something is up to date, it prints the exact localhost
 * URL to go to, every time. A page hash narrated where a URL belongs, or a recent block reading "the asks page
 * republished" with no address beside it, leaves the owner nothing to open.
 *
 * ## The criterion is lexical, and a pointer is anything the owner can open
 *
 * A claim is `published`, `republished`, `publishing` or `up to date` as a whole word. A pointer is an
 * `http(s)://` or `file://` URL, or an absolute filesystem path (`/…`, `~/…`, `$SLOPWEAVER_HOME/…`). Any URL
 * counts rather than only the console's own, so a line about a Slack post or a pull request is satisfied by
 * its permalink; canon names the console surfaces ({@link CONSOLE_SURFACES}) as the URL to reach for.
 *
 * The tense is the claim. `publishes` and a bare `publish` state a habit or an intent, not that something
 * happened: a lede reading "no chair publishes there again" names nothing the owner
 * should go and look at, and matching it would refuse a line with no claim in it.
 *
 * The test is per TEXT, not per sentence: a headline carrying the claim and the address in different sentences
 * passes. That is a floor, and it is stated as one — what it removes is the claim with nowhere to go at all.
 *
 * Pure: text in, the unpointed claim or `undefined` out. No I/O, no clock.
 */

import type { BriefingContent } from "../outbound/briefing/types.js";

/** The console's own surfaces, served by `yarn console` — the URLs a publish claim reaches for first. */
export const CONSOLE_SURFACES: readonly string[] = [
  "http://localhost:3000/queue",
  "http://localhost:3000/pull-requests",
  "http://localhost:3000/workstreams",
  "http://localhost:3000/fleet",
  "http://localhost:3000/alignment",
];

/** A publish or up-to-date claim, as a whole word or phrase. */
const CLAIM = /\b(?:re)?publish(?:ed|ing)\b|\bup[ -]to[ -]date\b/i;

/** Something the owner can open: a URL, or an absolute path. */
const POINTER = /\b(?:https?|file):\/\/\S+|(?:^|[\s(`"'])(?:~|\$SLOPWEAVER_HOME)?\/[\w.-]+\/\S*/;

/**
 * The claim a text makes with no pointer beside it.
 *
 * @param text the line as the owner reads it, a link run's URL included
 * @returns the claim as written, or `undefined` when there is none or the text names where to look
 */
export function unpointedPublishClaim({ text }: { text: string }): string | undefined {
  const claim = CLAIM.exec(text);
  if (claim === null || POINTER.test(text)) {
    return undefined;
  }
  return claim[0];
}

/**
 * The refusal for one unpointed claim, worded once so every surface says the same thing.
 *
 * @param claim the claim {@link unpointedPublishClaim} found
 * @returns one line naming the claim and the addresses that fix it
 */
export function publishClaimRefusal({ claim }: { claim: string }): string {
  return (
    `the line says "${claim}" and never says where the owner goes to see it. ` +
    `Name the exact URL — ${CONSOLE_SURFACES.join(", ")} — or the file path when the surface is not on the ` +
    "console, and say what moved rather than a page hash."
  );
}

/** One refused line: where it sits on the form, and what to tell the composer. */
export interface PublishClaimIssue {
  /** The form path of the refused field. */
  readonly path: readonly (string | number)[];
  /** The refusal, from {@link publishClaimRefusal}. */
  readonly message: string;
}

/**
 * Every composed headline on the briefing form that claims a publish with nowhere to go.
 *
 * Only the fields a chair COMPOSES are read — the lede and each recent block's headline. The alignment line
 * and its intake fold are generated by `slopweaver handover reconcile` and pasted verbatim, so a refusal
 * there would be one the composer cannot act on. A link run counts through its URL, which is where a
 * rendered link carries its address.
 *
 * @param lede the header's lede
 * @param recent the recent blocks, in page order
 * @returns one issue per refused field, in page order; empty when every claim names where to look
 */
export function publishClaimIssues({
  lede,
  recent,
}: {
  lede: BriefingContent;
  recent: readonly { readonly headline: BriefingContent }[];
}): readonly PublishClaimIssue[] {
  const fields = [
    { content: lede, path: ["header", "lede"] },
    ...recent.map((note, index) => ({ content: note.headline, path: ["recent", index, "headline"] })),
  ];
  return fields.flatMap(({ content, path }) => {
    const claim = unpointedPublishClaim({ text: pointableText({ content }) });
    return claim === undefined ? [] : [{ message: publishClaimRefusal({ claim }), path }];
  });
}

/**
 * One field's text with every link run's URL written beside its label.
 *
 * @param content the field's runs
 * @returns the text a pointer is looked for in
 */
function pointableText({ content }: { content: BriefingContent }): string {
  return content.map((run) => (run.kind === "link" ? `${run.text} ${run.url}` : run.text)).join(" ");
}
