/**
 * Emit `src/atlas/datadog/generated/responseBoundaries*.ts` and `responseInventory.ts` from the pinned
 * specifications and ONE census run.
 *
 * ```bash
 * yarn tsx tools/datadogResponseCensus.ts <census.json>                                   # take the census
 * yarn tsx tools/generateDatadogResponseBoundaries.ts <spec-dir> <census.json>            # write the boundaries
 * ```
 *
 * `<spec-dir>` holds `v1.yaml` and `v2.yaml` fetched from the immutable tag URLs in `generated/sdkLock.ts`, and
 * each is refused unless its digest matches its pin. Every rule about what is declared is `responseCodegen.ts`'s;
 * this file reads, partitions and writes.
 *
 * REFUSES, writing nothing, when any operation's boundary cannot be generated. Every refusal is collected first,
 * so one run names them all.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { parse } from "yaml";

import { DATADOG_API_ADMITTED } from "../src/atlas/datadog/apiAcquisition.js";
import { DATADOG_SPEC_PINS } from "../src/atlas/datadog/generated/sdkLock.js";
import { parseDatadogResponseCensus } from "../src/atlas/datadog/responseCensus.js";
import { datadogBoundarySource } from "../src/atlas/datadog/responseCodegen.js";
import { datadogLagInventory } from "../src/atlas/datadog/responseCodegenFields.js";
import { type DatadogCut, type DatadogSpecLag, datadogPlaceDepth } from "../src/atlas/datadog/responseCodegenPlace.js";
import { datadogResponseDeclaration } from "../src/atlas/datadog/responseDeclaration.js";
import type { DatadogSpec } from "../src/atlas/datadog/surfaceNaming.js";
import { isRecord } from "../src/lib/parsers.js";

/** How many files the boundaries are split across, so no one file is too large to review or type-check. */
const BATCHES = 4;
const OUTPUT_DIR = "src/atlas/datadog/generated";
const SPECS: readonly DatadogSpec[] = ["v1", "v2"];

/** Each pinned specification, refused unless its bytes are the pinned ones. */
function documentsIn({ dir }: { dir: string }): ReadonlyMap<DatadogSpec, Readonly<Record<string, unknown>>> {
  const documents = new Map<DatadogSpec, Readonly<Record<string, unknown>>>();
  for (const spec of SPECS) {
    const bytes = readFileSync(join(dir, `${spec}.yaml`));
    const digest = createHash("sha256").update(bytes).digest("hex");
    if (digest !== DATADOG_SPEC_PINS[spec].sha256) {
      throw new Error(`${spec}.yaml is sha256 ${digest}, not the pinned ${DATADOG_SPEC_PINS[spec].sha256}`);
    }
    const parsed: unknown = parse(bytes.toString("utf8"), { maxAliasCount: -1 });
    if (!isRecord(parsed)) {
      throw new Error(`${spec}.yaml is not a YAML mapping`);
    }
    documents.set(spec, parsed);
  }
  return documents;
}

/** One generated batch file. */
function batchFile({
  index,
  sources,
  takenAt,
}: {
  index: number;
  sources: readonly string[];
  takenAt: string;
}): string {
  const pins = SPECS.map((spec) => ` *   ${spec} sha256 ${DATADOG_SPEC_PINS[spec].sha256}`).join("\n");
  return `/**
 * GENERATED by \`tools/generateDatadogResponseBoundaries.ts\` from the pinned specifications and one structural
 * census of the live organisation — key paths, kinds and counts, never a value — taken ${takenAt}. GENERATED — do not
 * hand-edit: re-take the census, regenerate, and review the diff. \`responseCodegen.ts\` says what each declares.
 *
 * Batch ${String(index + 1)} of ${String(BATCHES)}. The specifications:
${pins}
 */
import { z } from "zod";

import { type DatadogResponseBoundary, defineDatadogResponseBoundary } from "../responseBoundary.js";

/** The response boundaries of batch ${String(index + 1)}, in registry order. */
export const DATADOG_RESPONSE_BOUNDARIES_${String(index + 1)}: readonly DatadogResponseBoundary[] = [
${sources.map((source) => `  ${source},`).join("\n")}
];
`;
}

/** The generated inventory: what was left unread, where the specification lags, what was never measured, and what answers a file. */
function inventoryFile({
  takenAt,
  cuts,
  lag,
  unmeasured,
  files,
}: {
  takenAt: string;
  cuts: readonly (DatadogCut & { readonly surface: string })[];
  lag: readonly (DatadogSpecLag & { readonly surface: string })[];
  unmeasured: readonly string[];
  files: readonly { readonly surface: string; readonly essence: string }[];
}): string {
  const lines = (rows: readonly unknown[]): string => rows.map((row) => `  ${JSON.stringify(row)},`).join("\n");
  return `/**
 * GENERATED by \`tools/generateDatadogResponseBoundaries.ts\` beside the response boundaries, from the census taken
 * ${takenAt}. GENERATED — do not hand-edit: its length is one row per place, which is its content.
 */
import type { ResponseJsonKind } from "../../kit/responseStructure.js";
import type { DatadogCutReason } from "../responseSpecNode.js";

/** The instant the census every measured boundary was declared from was taken. */
export const DATADOG_RESPONSE_CENSUS_TAKEN_AT = ${JSON.stringify(takenAt)};

/** Every place a boundary leaves unread, by operation and census path. */
export const DATADOG_RESPONSE_CUTS: readonly { readonly surface: string; readonly path: string; readonly reason: DatadogCutReason }[] = [
${lines(cuts)}
];

/**
 * Every place the census measured a key or kind the pinned specification does not declare there, by operation,
 * path and lag. Each is ADMITTED: the boundary declares what the live answer carries. A new row in this file's diff
 * is the specification falling behind; the list records no review of it.
 */
export const DATADOG_RESPONSE_SPEC_LAG: readonly { readonly surface: string; readonly path: string; readonly lag: "key" | ResponseJsonKind }[] = [
${lines(lag)}
];

/** Every operation whose boundary declares the specification's names only, since it never answered 2xx. */
export const DATADOG_RESPONSE_UNMEASURED: readonly string[] = [
${lines(unmeasured)}
];

/** Every operation the specification declares as answering a file rather than JSON, which no boundary reads. */
export const DATADOG_RESPONSE_FILE_OPERATIONS: readonly { readonly surface: string; readonly essence: string }[] = [
${lines(files)}
];
`;
}

const dir = process.argv.at(2);
const censusPath = process.argv.at(3);
if (dir === undefined || censusPath === undefined) {
  throw new Error("usage: yarn tsx tools/generateDatadogResponseBoundaries.ts <spec-dir> <census.json>");
}
const documents = documentsIn({ dir });
// The census is this repository's own output, written by `tools/datadogResponseCensus.ts`.
const read = parseDatadogResponseCensus({ text: readFileSync(censusPath, "utf8") });
if (read.isErr()) {
  throw new Error(`${censusPath} is not a Datadog response census:\n${read.error.join("\n")}`);
}
const census = read.value;
const sources: string[] = [];
const refusals: string[] = [];
const cuts: (DatadogCut & { readonly surface: string })[] = [];
const unmeasured: string[] = [];
const files: { readonly surface: string; readonly essence: string }[] = [];
const lag: (DatadogSpecLag & { readonly surface: string })[] = [];
for (const row of DATADOG_API_ADMITTED) {
  const document = documents.get(row.spec)!;
  const declaration = datadogResponseDeclaration({ document, method: row.method, path: row.path });
  if (declaration.isErr()) {
    refusals.push(`${row.name}: ${declaration.error.message}`);
    continue;
  }
  if (declaration.value.media === "file") {
    files.push({ essence: declaration.value.essence, surface: row.name });
    continue;
  }
  // An operation that never answered 2xx has no tally, and its boundary declares the specification's names only.
  const measured = Object.hasOwn(census.operations, row.name);
  const generated = datadogBoundarySource({
    census: measured ? census.operations[row.name]! : null,
    document,
    schema: declaration.value.schema,
    surface: row.name,
  });
  if (generated.isErr()) {
    refusals.push(generated.error.message);
    continue;
  }
  sources.push(generated.value.source);
  cuts.push(...generated.value.cuts.map((cut) => ({ surface: row.name, ...cut })));
  lag.push(...datadogLagInventory({ lag: generated.value.lag, surface: row.name }));
  if (!generated.value.measured) {
    unmeasured.push(row.name);
  }
}
if (refusals.length > 0) {
  throw new Error(`${String(refusals.length)} refusal(s), nothing written:\n${refusals.join("\n")}`);
}
const perBatch = Math.ceil(sources.length / BATCHES);
for (let index = 0; index < BATCHES; index += 1) {
  const batch = sources.slice(index * perBatch, (index + 1) * perBatch);
  writeFileSync(
    `${OUTPUT_DIR}/responseBoundaries${String(index + 1)}.ts`,
    batchFile({ index, sources: batch, takenAt: census.takenAt }),
  );
}
writeFileSync(
  `${OUTPUT_DIR}/responseInventory.ts`,
  inventoryFile({ cuts, files, lag, takenAt: census.takenAt, unmeasured }),
);
// The deepest census path, which `responseCodegenPlace.ts`'s MAX_DEPTH is sized from.
const depths = Object.values(census.operations).flatMap((operation) =>
  Object.keys(operation.paths).map((path) => datadogPlaceDepth({ path })),
);
const deepest = depths.reduce((most, depth) => Math.max(most, depth), 0);
process.stdout.write(
  `${String(sources.length)} boundaries in ${String(BATCHES)} batches: ${String(sources.length - unmeasured.length)} measured, ${String(unmeasured.length)} names only; ${String(cuts.length)} cut(s); ${String(lag.length)} spec lag place(s); ${String(files.length)} file operation(s); deepest census path ${String(deepest)} levels\n`,
);
